import config


def _today() -> str:
    if config.LEGAL_DATE:
        return config.LEGAL_DATE
    moment = datetime.now(timezone(timedelta(hours=3)))
    return moment.strftime("%d.%m.%Y")


def _operator() -> str:
    """Кто оказывает услугу.

    По умолчанию — только название сервиса, без ИП/ООО и ИНН: банк на
    согласовании просил убрать эти сведения из бота и документов.
    Данные никуда не делись, они лежат в LEGAL_* и включаются обратно
    переменной LEGAL_SHOW_REQUISITES, когда касса зарегистрирована.
    """
    if not (config.LEGAL_SHOW_REQUISITES and config.LEGAL_NAME):
        return escape(config.SERVICE_NAME)
    parts = [escape(config.LEGAL_NAME)]
    if config.LEGAL_INN:
        parts.append(f"ИНН {escape(config.LEGAL_INN)}")
    return ", ".join(parts)


def _review_mark() -> str:
    """Кодовое слово проверяющего. Пусто — ничего не показываем."""
    if not config.REVIEW_CODE:
        return ""
    return (
        '<p class="code">Кодовое слово: <b>'
        + escape(config.REVIEW_CODE)
        + "</b></p>"
    )


def _contacts_html() -> str:
    """Как связаться. Единственный способ — обращение в приложении.

    Личных контактов здесь нет намеренно: у обращения из приложения есть
    номер, переписка и статус, и оно не теряется. Написанное же в личку
    живому человеку не отслеживается никак — ни им самим, ни тем более
    тем, кто написал.

    Почта остаётся в настройках (`LEGAL_EMAIL`) и на страницу не
    выводится. Если её однажды потребует касса или банк, вернуть строку
    сюда — минутное дело; убирать переменную ради этого не стоит.
    """
    rows = [
        "<li>Обращение в поддержку — в приложении бота, раздел "
        "«Поддержка». У каждого обращения есть номер и переписка, "
        "ответ приходит в чат с ботом.</li>",
        "<li>К обращению можно приложить скриншот или запись экрана.</li>",
    ]
    if config.BOT_USERNAME:
        rows.insert(
            0,
            f'<li>Бот сервиса: <a href="https://t.me/{escape(config.BOT_USERNAME)}">'
            f"@{escape(config.BOT_USERNAME)}</a></li>",
        )
    return "\n".join(rows)


